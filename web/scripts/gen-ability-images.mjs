/**
 * Mirror ability, item and weapon icons into src/assets/abilities/.
 *
 * A replay names what a hero cast by its internal class name -- `synth_barrage`,
 * `upgrade_warp_stone` -- and some of those are old codenames nothing like what the game
 * shows (`ability_unicorn_luminousstrike` is Celeste's Radiant Daggers). Its damage
 * events name what dealt a hit by deadlock-api's numeric id instead. deadlock-api.com
 * publishes the display name, id and icon of each, so this mirrors all three and commits
 * the result, the same arrangement as gen-hero-images.mjs.
 *
 * Every ability, item and weapon with an icon: a cast names an ability or an item's
 * active, and a hit names whatever dealt it -- which includes passive items (a bleed, a
 * proc) and hero weapons.
 *
 * Usage:
 *     npm run assets:abilities
 */

import { mkdir, writeFile, rm } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'src', 'assets', 'abilities')
const MANIFEST = join(ROOT, 'src', 'abilities', 'manifest.ts')

const API = 'https://api.deadlock-api.com/v1/assets/items'
// The API 403s a request without one.
const HEADERS = { 'User-Agent': 'deadlock-stats-api (github)', Accept: 'application/json' }

/** A few requests at once: several hundred files one at a time is slow, all at once
 * is rude to someone else's bucket. */
const PARALLEL = 8

/** deadlock-api's item types, and what the interface calls each. */
const KINDS = { ability: 'ability', upgrade: 'item', weapon: 'weapon' }

async function main() {
  console.log(`Fetching from ${API} ...`)
  const response = await fetch(API, { headers: HEADERS })
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}`)
  const items = await response.json()

  const known = items
    .filter((item) => item.class_name && KINDS[item.type])
    .sort((a, b) => a.class_name.localeCompare(b.class_name))
  const wanted = known.filter((item) => item.image_webp)
  console.log(`  ${wanted.length} abilities, items and weapons with icons`)

  await rm(OUT, { recursive: true, force: true })
  await mkdir(OUT, { recursive: true })

  let saved = 0
  const missing = []
  let bytes = 0
  let next = 0

  // The class name is the filename: it is what a cast says, and what an id maps to.
  const worker = async () => {
    while (next < wanted.length) {
      const item = wanted[next++]
      const res = await fetch(item.image_webp, { headers: { 'User-Agent': HEADERS['User-Agent'] } })
      if (!res.ok) {
        missing.push(`${item.class_name} (${res.status})`)
        continue
      }
      const buffer = Buffer.from(await res.arrayBuffer())
      bytes += buffer.byteLength
      await writeFile(join(OUT, `${item.class_name}.webp`), buffer)
      saved++
      process.stdout.write(`\r  downloaded ${saved}/${wanted.length}`)
    }
  }
  await Promise.all(Array.from({ length: PARALLEL }, worker))

  console.log(`\n  ${(bytes / 1024 / 1024).toFixed(1)} MB written to src/assets/abilities/`)
  if (missing.length) console.log(`  missing from the bucket: ${missing.join(', ')}`)

  // Many weapons are listed with their class name as their name: no name at all, as far
  // as a reader is concerned, so they are left out and the interface says "Weapon".
  const named = known.filter((item) => item.name && item.name !== item.class_name)
  const names = named
    .map((item) => `  ${item.class_name}: ${JSON.stringify(item.name)},`)
    .join('\n')
  // What the item build needs to lay an item out the way the shop does: its category,
  // tier and price, and what it was built from.
  const shop = known
    .filter((item) => item.type === 'upgrade' && item.item_slot_type)
    .sort((a, b) => a.id - b.id)
    .map((item) => {
      const info = {
        slot: item.item_slot_type,
        tier: item.item_tier ?? 0,
        cost: item.cost ?? 0,
        ...(item.component_items?.length ? { components: item.component_items } : {}),
      }
      return `  ${item.id}: ${JSON.stringify(info)},`
    })
    .join('\n')
  const ids = [...known]
    .sort((a, b) => a.id - b.id)
    .map((item) => `  ${item.id}: ['${item.class_name}', '${KINDS[item.type]}'],`)
    .join('\n')

  await mkdir(dirname(MANIFEST), { recursive: true })
  await writeFile(
    MANIFEST,
    `/**
 * Ability, item and weapon names and ids. Generated by scripts/gen-ability-images.mjs;
 * do not edit.
 *
 * A replay's cast events name what was cast by class name; its damage events name what
 * dealt a hit by numeric id. An icon, where there is one, is
 * src/assets/abilities/<class name>.webp.
 */

/** Class name -> display name. */
export const ABILITY_NAMES: Record<string, string> = {
${names}
}

/** deadlock-api id -> class name, and what kind of thing it is. */
export const SOURCES: Record<number, [string, 'ability' | 'item' | 'weapon']> = {
${ids}
}

/** Item id -> its shop category, tier, price in souls, and the class names of the items
 * it upgrades from. */
export const ITEMS: Record<
  number,
  { slot: 'weapon' | 'vitality' | 'spirit'; tier: number; cost: number; components?: string[] }
> = {
${shop}
}
`,
    'utf-8',
  )
  console.log(`  manifest: ${named.length} names, ${known.length} ids, ${saved} icons`)
}

main().catch((error) => {
  console.error(error.message)
  process.exit(1)
})
