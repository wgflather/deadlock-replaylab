/**
 * Refresh the map's world radius in src/map/manifest.ts.
 *
 * Replays give positions in world units; drawing them needs the scale that ties those to
 * the picture. deadlock-api.com publishes it, so this mirrors it and commits the result --
 * nothing here runs at request time. Same arrangement as gen-hero-images.mjs.
 *
 * The picture itself is not fetched. What the API publishes is a 512px composite, and
 * src/assets/map/minimap.webp is the artwork at native scale with its decorative surround
 * cropped away -- see the note in src/map/index.ts. This only keeps the number honest.
 *
 * Usage:
 *     npm run assets:map
 */

import { mkdir, writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const MANIFEST = join(ROOT, 'src', 'map', 'manifest.ts')

const API = 'https://api.deadlock-api.com/v1/assets/map'
// The API 403s a request without one.
const HEADERS = { 'User-Agent': 'deadlock-stats-api (github)', Accept: 'application/json' }

async function main() {
  console.log(`Fetching from ${API} ...`)
  const response = await fetch(API, { headers: HEADERS })
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}`)
  const map = await response.json()

  if (!Number.isFinite(map.radius)) throw new Error('map assets carry no radius')

  await mkdir(dirname(MANIFEST), { recursive: true })
  await writeFile(
    MANIFEST,
    `/**
 * Map metadata. Generated by scripts/gen-map-image.mjs; do not edit.
 *
 * The playable area is a disc of this many world units about the origin. The map image
 * reaches a little further -- see MAP_IMAGE_RADIUS in ./index.ts, which is what a
 * position is actually measured against.
 */
export const MAP_RADIUS = ${map.radius}
`,
    'utf8',
  )
  console.log(`  radius ${map.radius} -> ${MANIFEST.replace(ROOT, '.')}`)
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
