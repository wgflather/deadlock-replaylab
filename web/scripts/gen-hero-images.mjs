/**
 * Mirror hero icons and portraits into src/assets/heroes/.
 *
 * The GC hands back bare integers -- `hero_id 7` -- and the artwork for them lives in the
 * game's resource files. deadlock-api.com publishes both, so this mirrors the two sizes
 * the interface uses and commits the result; nothing here runs at request time. It is the
 * same arrangement as gc-client/scripts/gen_assets.py, which mirrors the *names* from the
 * same source.
 *
 * WebP only. The API offers PNG of each, at roughly twice the bytes, and every browser
 * that can run this app reads WebP.
 *
 * Usage:
 *     npm run assets:heroes
 */

import { mkdir, writeFile, rm } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'src', 'assets', 'heroes')
const MANIFEST = join(ROOT, 'src', 'heroes', 'manifest.ts')

const API = 'https://api.deadlock-api.com/v1/assets/heroes'
// The API 403s a request without one.
const HEADERS = { 'User-Agent': 'deadlock-stats-api (github)', Accept: 'application/json' }

/** 128x128 square, for a table row. */
const ICON = 'icon_image_small_webp'
/** 280x380 portrait, for anywhere a hero is the subject rather than a label. */
const PORTRAIT = 'icon_hero_card_webp'

/** Filenames come from the hero name, so the folder is readable; ids live in the manifest. */
function slugify(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

async function main() {
  console.log(`Fetching from ${API} ...`)
  const response = await fetch(API, { headers: HEADERS })
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}`)
  const heroes = await response.json()

  // Every hero the API knows, not just the currently playable ones: match history can
  // name a hero that has since been disabled, and a row with no picture is worse than a
  // few unused files.
  const usable = heroes
    .filter((hero) => hero.name && hero.images?.[ICON] && hero.images?.[PORTRAIT])
    .sort((a, b) => a.id - b.id)

  const skipped = heroes.length - usable.length
  console.log(`  ${usable.length} heroes with artwork${skipped ? `, ${skipped} without` : ''}`)

  for (const dir of ['icons', 'portraits']) {
    await rm(join(OUT, dir), { recursive: true, force: true })
    await mkdir(join(OUT, dir), { recursive: true })
  }

  const entries = []
  const missing = []
  let bytes = 0

  for (const hero of usable) {
    const slug = slugify(hero.name)
    const got = {}

    for (const [dir, field] of [
      ['icons', ICON],
      ['portraits', PORTRAIT],
    ]) {
      // The listing promises a URL the bucket does not always have -- Boho's portrait
      // 404s today. One absent file is not a reason to abandon the other 54 heroes, so
      // it is skipped and reported; the lookup falls back to initials for it.
      const res = await fetch(hero.images[field], { headers: { 'User-Agent': HEADERS['User-Agent'] } })
      if (!res.ok) {
        missing.push(`${hero.name} ${dir.slice(0, -1)} (${res.status})`)
        continue
      }
      const buffer = Buffer.from(await res.arrayBuffer())
      bytes += buffer.byteLength
      await writeFile(join(OUT, dir, `${slug}.webp`), buffer)
      got[dir] = true
    }

    // An id with no artwork at all has nothing to point at.
    if (got.icons || got.portraits) entries.push({ id: hero.id, name: hero.name, slug })
    process.stdout.write(`\r  downloaded ${entries.length}/${usable.length}`)
  }

  console.log(`\n  ${(bytes / 1024 / 1024).toFixed(1)} MB written to src/assets/heroes/`)
  if (missing.length) console.log(`  missing from the bucket: ${missing.join(', ')}`)

  await mkdir(dirname(MANIFEST), { recursive: true })
  const body = entries.map((e) => `  ${e.id}: '${e.slug}', // ${e.name}`).join('\n')
  await writeFile(
    MANIFEST,
    `/**
 * hero_id -> artwork slug. Generated by scripts/gen-hero-images.mjs; do not edit.
 *
 * Ids are the GC's own, so they survive a hero being renamed. The slug is the filename
 * under src/assets/heroes/{icons,portraits}/.
 */
export const HERO_SLUGS: Record<number, string> = {
${body}
}
`,
    'utf-8',
  )
  console.log(`  manifest: ${entries.length} heroes`)
}

main().catch((error) => {
  console.error(error.message)
  process.exit(1)
})
